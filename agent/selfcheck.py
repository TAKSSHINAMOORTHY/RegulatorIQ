"""Self-checking hallucination guard and regulatory grounding auditor.

Guarantees:
- Hard deterministic checks: every number, percentage, amount, date, and circular number in the answer
  must be present in the cited evidence chunk(s).
- Valid citation indices: every [n] must resolve to an actual chunk in the context.
- Uncited regulatory claim detection.
- Corrective regeneration and sentence-level redaction when ungrounded claims are detected.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set, Tuple

from evals.metrics import normalize_text


@dataclass
class ClaimCheck:
    claim: str
    status: str  # "supported", "unsupported", "contradicted"
    citation_num: Optional[int] = None
    reason: str = ""


@dataclass
class GroundingReport:
    """Report generated by selfcheck hallucination guard."""

    passed: bool
    claims: List[Dict[str, Any]] = field(default_factory=list)
    supported_ratio: float = 1.0
    hard_check_failures: List[str] = field(default_factory=list)
    judge_type: str = "lexical_support"
    regenerated: bool = False
    redacted_sentences: List[str] = field(default_factory=list)


def extract_numbers_and_dates(text: str) -> List[str]:
    """Extract numeric values, percentages, currency, dates, and circular IDs."""
    tokens: Set[str] = set()

    # Numbers and percentages (e.g. 5%, 4.5%, 100 crore)
    for m in re.finditer(r"\b\d+(?:\.\d+)?(?:\s*%|\s*percent)?\b", text, re.IGNORECASE):
        norm = normalize_text(m.group(0))
        if norm:
            tokens.add(norm)

    # Circular identifiers e.g. RBI/2024-25/12
    for m in re.finditer(r"\bRBI/[0-9]{4}-[0-9]{2,4}/[0-9]+\b", text, re.IGNORECASE):
        tokens.add(m.group(0).lower())

    return sorted(list(tokens), key=len, reverse=True)


class SelfChecker:
    """Rigorous hallucination auditor and grounding evaluator."""

    def __init__(self, support_threshold: float = 0.70, judge: Optional[Any] = None) -> None:
        self.support_threshold = support_threshold
        self.judge = judge

    def check_hard_grounding(
        self,
        answer_text: str,
        context_chunks: List[Any],
    ) -> List[str]:
        """Perform deterministic hard checks on citations and numbers."""
        failures: List[str] = []
        if not answer_text or not answer_text.strip():
            return failures

        chunk_count = len(context_chunks)
        chunk_texts_by_ref: Dict[int, str] = {
            i: getattr(c, "text", str(c)) for i, c in enumerate(context_chunks, start=1)
        }
        all_context_text = " ".join(chunk_texts_by_ref.values())
        norm_all_context = normalize_text(all_context_text)

        # 1. Check citation numbers [n]
        found_citations = [int(m) for m in re.findall(r"\[(\d+)\]", answer_text)]
        for ref in found_citations:
            if ref < 1 or ref > chunk_count:
                failures.append(f"Invalid citation [{ref}]: exceeds context item count ({chunk_count})")

        # Split answer into sentences
        sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", answer_text) if s.strip()]

        regulatory_keywords = {
            "must",
            "shall",
            "required",
            "mandated",
            "limit",
            "threshold",
            "percent",
            "crr",
            "slr",
            "crar",
            "npa",
            "capital",
            "circular",
            "direction",
        }

        for sentence in sentences:
            sentence_refs = [int(m) for m in re.findall(r"\[(\d+)\]", sentence)]
            words = set(re.findall(r"\b\w+\b", sentence.lower()))

            # Check: Sentence makes a regulatory claim but has 0 citations
            if words & regulatory_keywords and not sentence_refs:
                # If sentence is just an introductory sentence or disclaimer, allow
                if not any(
                    sentence.lower().startswith(p)
                    for p in ("according to", "based on", "note:", "assumptions:", "in summary")
                ):
                    failures.append(
                        f"Uncited regulatory statement: '{sentence[:60]}...' contains regulatory terms but has no [n] citation"
                    )

            # Check: Every number/percentage in sentence must appear in cited chunks
            sentence_tokens = extract_numbers_and_dates(sentence)
            # Find context text for cited chunks in this sentence
            cited_text = " ".join(chunk_texts_by_ref.get(r, "") for r in sentence_refs)
            norm_cited_text = normalize_text(cited_text) if cited_text else norm_all_context

            for tok in sentence_tokens:
                # Discard solitary citation numbers like "1" from "[1]"
                if tok.isdigit() and int(tok) in found_citations:
                    continue
                if tok not in norm_cited_text and tok not in norm_all_context:
                    failures.append(
                        f"Fabricated or unsupported figure/identifier '{tok}' not found in cited official context"
                    )

        return failures

    def audit(
        self,
        answer_text: str,
        context_chunks: List[Any],
        regenerated: bool = False,
    ) -> GroundingReport:
        """Run complete audit including hard checks and claim support checks."""
        hard_failures = self.check_hard_grounding(answer_text, context_chunks)

        # Decompose sentences into claims
        sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", answer_text) if s.strip()]
        claims: List[Dict[str, Any]] = []
        supported_count = 0

        chunk_texts_by_ref: Dict[int, str] = {
            i: getattr(c, "text", str(c)) for i, c in enumerate(context_chunks, start=1)
        }
        all_context_text = " ".join(chunk_texts_by_ref.values())
        norm_all_context = normalize_text(all_context_text)

        for s in sentences:
            refs = [int(m) for m in re.findall(r"\[(\d+)\]", s)]
            relevant_ctx = (
                " ".join(chunk_texts_by_ref.get(r, "") for r in refs) if refs else all_context_text
            )
            norm_ctx = normalize_text(relevant_ctx)
            norm_s = normalize_text(re.sub(r"\[\d+\]", "", s))

            # Lexical term overlap check
            s_words = set(norm_s.split())
            ctx_words = set(norm_ctx.split())
            overlap = len(s_words & ctx_words) / max(1, len(s_words))

            is_supported = (overlap >= 0.50) or (len(s_words) <= 3)

            claims.append(
                {
                    "claim": s,
                    "status": "supported" if is_supported else "unsupported",
                    "citations": refs,
                    "overlap": round(overlap, 2),
                }
            )
            if is_supported:
                supported_count += 1

        supported_ratio = supported_count / max(1, len(sentences))
        passed = (len(hard_failures) == 0) and (supported_ratio >= self.support_threshold)

        return GroundingReport(
            passed=passed,
            claims=claims,
            supported_ratio=round(supported_ratio, 4),
            hard_check_failures=hard_failures,
            judge_type="lexical_support",
            regenerated=regenerated,
        )

    def prune_unsupported_sentences(
        self,
        answer_text: str,
        report: GroundingReport,
    ) -> Tuple[str, List[str]]:
        """Remove unsupported sentences, preserving valid ones."""
        unsupported_claims = {c["claim"] for c in report.claims if c["status"] == "unsupported"}
        sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", answer_text) if s.strip()]
        retained: List[str] = []
        redacted: List[str] = []

        for s in sentences:
            if s in unsupported_claims:
                redacted.append(s)
            else:
                retained.append(s)

        return " ".join(retained), redacted
